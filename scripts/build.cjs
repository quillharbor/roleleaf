const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../tipsy-exporter');
const core = fs.readFileSync(path.join(root, 'core.js'), 'utf8');
// Each execution world gets a unique, self-contained resource. Do not list
// the same core.js resource in multiple content-script world declarations.
for (const [target, entry] of [['page.bundle.js', 'capture.js'], ['bridge.bundle.js', 'content.js']]) {
  const files = target === 'page.bundle.js' ? ['bot-creator.js', 'chat.js', entry, 'chat-capture.js', 'creator-capture.js'] : ['bot-model.js', 'bot-creator.js', 'sidebar.js', 'creator-bridge.js', entry];
  fs.writeFileSync(path.join(root, target), '// Generated by scripts/build.cjs. Edit source files, then rebuild.\n' + core + '\n;\n' + files.map(file => fs.readFileSync(path.join(root, file), 'utf8')).join('\n;\n'));
}
console.log('Built independent MAIN and ISOLATED bundles');

for (const [target, files] of [
 ['cai-page.bundle.js',['core.js','bot-model.js','cai.js','cai-capture.js']],
 ['cai-bridge.bundle.js',['core.js','bot-model.js','bot-creator.js','sidebar.js','creator-bridge.js','cai-bridge.js']]
]) fs.writeFileSync(path.join(root,target),'// Generated by scripts/build.cjs.\n'+files.map(file=>fs.readFileSync(path.join(root,file),'utf8')).join('\n;\n'));
